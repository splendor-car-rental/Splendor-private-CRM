function normalizeExactKey(value: string): string {
  return value.trim().replace(/\s+/g, ' ').toLowerCase();
}

function applyDynamicPatterns(value: string): string {
  return value
    .replace(/\b(\d+)\s+Avail\b/gi, '$1 متاح')
    .replace(/\b(\d+)\s+Active\b/gi, '$1 نشط')
    .replace(/\b(\d+)\s+Review\b/gi, '$1 للمراجعة')
    .replace(/\b(\d+)\s+Unmatched\b/gi, '$1 غير مطابق')
    .replace(/\b(\d+)\s+Passed\b/gi, '$1 ناجح')
    .replace(/\b(\d+)\s+Days?\b/gi, '$1 أيام')
    .replace(/\b(\d+)\s+Months?\b/gi, '$1 أشهر')
    .replace(/\b(\d+)\s+Years?\b/gi, '$1 سنوات')
    .replace(/\b(\d+(?:\.\d+)?)\s*ms\b/gi, '$1 مللي ثانية');
}

function applyTokenTranslations(value: string): string {
  return value.replace(/\b[A-Za-z][A-Za-z0-9.&/-]*\b/g, (token) => {
    const normalized = token.replace(/[.,:;!?]+$/g, '').toUpperCase();
    return TOKEN_TRANSLATIONS[normalized] ?? token;
  });
}

/**
 * Normalizes interface copy while Arabic mode is active.
 *
 * safe: only exact phrases, dynamic counters and known technical terms inside
 * already-Arabic text are touched. This protects customer/company/vehicle data.
 * aggressive: intended for UI chrome (buttons, labels, headings, placeholders,
 * aria labels, table headings). Known English UI tokens are translated too.
 */
export function translateArabicUiText(input: string, mode: ArabicTranslationMode = 'safe'): string {
  if (!input || !LATIN_RE.test(input)) return input;
  if (EMAIL_OR_URL_RE.test(input.trim())) return input;

  const exact = EXACT_UI_TRANSLATIONS[normalizeExactKey(input)];
  if (exact) return exact;

  let result = applyDynamicPatterns(input);
  const alreadyArabic = ARABIC_RE.test(result);

  // In normal content, do not rewrite pure-English values because they may be
  // customer names, supplier names, vehicle makes/models or external identifiers.
  if (mode === 'safe' && !alreadyArabic) return result;

  for (const [pattern, replacement] of PHRASE_REPLACEMENTS) {
    result = result.replace(pattern, replacement);
  }

  result = applyDynamicPatterns(result);
  result = applyTokenTranslations(result);

  return result;
}

export function containsLatinUiText(value: string): boolean {
  return LATIN_RE.test(value) && !EMAIL_OR_URL_RE.test(value.trim());
}
